/** `shown` is the command as the person typed it (a 1.6 word), `cmd` the command it runs as. */
export function printCommandHelp(cmd: string, shown = cmd): void {
  const h = helpFor(cmd);
  console.log(h ? `monomem ${shown}\n\n${h}\n\nAll commands: monomem help --all` : `monomem ${shown}: no extra options. All commands: monomem help --all`);
}

/** The help lines for one command, taken from the full help (so there is one text to keep right). */
export function helpFor(given: string): string | null {
  // An old name shows the help of the command it is now (quarantine -> review, token -> keys).
  const cmd = Object.hasOwn(OLD_COMMANDS, given) ? OLD_COMMANDS[given].split(" ")[0] : given === "taint" ? "settings" : given;
  const orig = console.log;
  let buf = "";
  console.log = (s?: unknown): void => void (buf += String(s ?? "") + "\n");
  try {
    usage(true);
  } finally {
    console.log = orig;
  }
  const out: string[] = [];
  let on = false;
  for (const line of buf.split("\n")) {
    const head = /^ {2}(\S+)/.exec(line);
    // Every command word on a head line counts ("  show <id> | ls [--ns x] | edit <id> | forget <id>" is ls's line too).
    const words = head ? [...line.matchAll(/(?:^ {2}|\| )([a-z-]+)/g)].map((m) => m[1]) : [];
    if (head) on = head[1].split("|").includes(cmd) || words.includes(cmd) || (cmd === "scrub" && head[1] === "purge-deleted");
    else if (!/^ {6,}/.test(line)) on = false;
    if (on) out.push(line);
  }
  return out.length ? out.join("\n") : null;
}
